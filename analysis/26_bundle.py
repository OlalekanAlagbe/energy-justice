"""Bundle the chapter JSON into one script the page can read over file://.

Browsers refuse fetch() for local files, so a site that fetched its JSON would
work on GitHub Pages and break when someone opens docs/index.html straight from
the folder. This writes every docs/data/*.json into docs/data/bundle.js as one
window.EJ_DATA object, which a plain script tag can load from anywhere.

The JSON files stay the canonical, diffable copies. This file is generated and
should not be edited by hand.

Run from the repository root, after the chapter build scripts:
  python analysis/26_bundle.py
"""
import json
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "docs" / "data"
OUT = DATA / "bundle.js"


def main():
    files = sorted(p for p in DATA.glob("*.json"))
    if not files:
        raise SystemExit("no JSON found in docs/data, run the chapter build scripts first")

    payload = {}
    for p in files:
        payload[p.stem] = json.loads(p.read_text(encoding="utf-8"))

    header = (
        "/* Generated by analysis/26_bundle.py on %s. Do not edit.\n"
        "   Source of truth is the individual JSON files in this folder.\n"
        "   Keys: %s */\n"
    ) % (date.today().isoformat(), ", ".join(sorted(payload)))

    body = "window.EJ_DATA = " + json.dumps(payload, separators=(",", ":")) + ";\n"
    OUT.write_text(header + body, encoding="utf-8")

    size_kb = OUT.stat().st_size / 1024
    print("wrote %s  (%d datasets, %.1f KB)" % (OUT.relative_to(ROOT), len(payload), size_kb))
    for k in sorted(payload):
        n = len(payload[k].get("rows", payload[k].get("series", [])))
        print("   %-28s %d rows" % (k, n))


if __name__ == "__main__":
    main()
